SPOILER = b"\xef\xbb\xbfArchipelago Version 0.6.8  -  Seed: 20362750649453646926\n\nPlando Options:   None\n"
DEV_SEED = 20362750649453646926
DEV_PLANDO = "connections, texts, bosses"


def zipped(entries: dict[str, bytes]) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, content in entries.items():
            archive.writestr(name, content)
    return buffer.getvalue()


def test_spoiler_logs_give_the_seed():
    spoiler = read_spoiler("AP_1_Spoiler.txt", SPOILER)
    assert (spoiler.seed, spoiler.plando, spoiler.version) == (DEV_SEED, "None", "0.6.8")
    assert read_spoiler("AP_1.zip", zipped({"AP_1/AP_1_Spoiler.txt": SPOILER, "AP_1/x.apz5": b""})) == spoiler

    without_plando = read_spoiler("s.txt", SPOILER.split(b"\n\n")[0])
    assert without_plando.plando == "bosses, connections, texts"

    with pytest.raises(LogicError, match="pas de spoiler log"):
        read_spoiler("AP_1.zip", zipped({"AP_1.archipelago": b""}))
    with pytest.raises(LogicError, match="Zip illisible"):
        read_spoiler("AP_1.zip", b"nope")
    with pytest.raises(LogicError, match="pas un spoiler log"):
        read_spoiler("notes.txt", b"hello")


def test_the_regenerated_seed_must_be_the_room():
    state = RoomState("x:1", seed_name="123", slots={1: SlotInfo(1, "Alice", "A"), 2: SlotInfo(2, "Bob", "B")})
    check_room(Generated("123", "0.6.8", "f", {1: ("Alice", "A"), 2: ("Bob", "B")}), state)
    state.seed_name = "W123"  # generated by a WebHost from yamls
    check_room(Generated("123", "0.6.8", "f", {1: ("Alice", "A"), 2: ("Bob", "B")}), state)

    with pytest.raises(LogicError, match="la seed ne correspond pas"):
        check_room(Generated("124", "0.6.8", "f", {1: ("Alice", "A"), 2: ("Bob", "B")}), state)
    with pytest.raises(LogicError, match="mêmes joueurs"):
        check_room(Generated("123", "0.6.8", "f", {1: ("Alice", "A"), 2: ("Bob", "C")}), state)


def test_panel_shows_who_is_blocked():
    state, progress = make_room()
    progress.apply_baseline(Baseline({1: {1}, 2: {2}, 3: {3}}, {1: 10, 2: 10, 3: 10}))
    logic = {
        1: SlotLogic(frozenset({4, 5, 6}), False),
        2: SlotLogic(frozenset(), False),
        3: SlotLogic(frozenset(), True),
    }

    text = view_text(panel_view("Async", state, progress, since=T0, logic=logic))
    assert "· 0/3 goals · 🔒 1 bloqué" in text
    assert "Alice · *Super Metroid* · 🔓 3 checks en logique" in text
    assert "Bob · *Super Metroid* · 🔒 **bloqué**" in text
    assert "Carol · *Super Metroid* · 🔓 objectif faisable" in text

    progress.apply(ev.GoalReached(2))
    text = view_text(panel_view("Async", state, progress, since=T0, logic=logic))
    assert "· 1/3 goals · 🔓 aucun bloqué" in text and "bloqué**" not in text
    assert "🔒" not in view_text(panel_view("Async", state, progress, since=T0))

    assert "🔓 3 checks en logique" in view_text(player_status_view(1, state, progress, {}, logic))


async def start_dev_worker(files=None):
    files = files or [(f"Players/{p.name}", p.read_bytes()) for p in sorted((DEV_DIR / "players").glob("*.yaml"))]
    return await LogicWorker.start(AP_DIR / ".venv" / "bin" / "python", AP_DIR, DEV_SEED, DEV_PLANDO, files)


@requires_ap_server
async def test_playing_only_what_is_in_logic_finishes_the_seed():
    worker, generated = await start_dev_worker()
    try:
        assert generated.seed_name == SEEDS[-1].stem.removeprefix("AP_")
        assert generated.slots == {1: ("Alice", "Celeste 64"), 2: ("Bob", "A Short Hike"), 3: ("Carol", "ChecksFinder")}
        for slot in generated.slots:
            assert await worker.placements(slot)

        # Carol alone runs out of things to do: blocked until the others send her items.
        checked: dict[int, set[int]] = {1: set(), 2: set(), 3: set()}
        while (carol := (await worker.evaluate(checked))[3]).locations:
            checked[3] |= carol.locations
        assert carol.blocked

        # Everyone doing only what is in logic reaches every goal: the logic is the seed's.
        rounds = 0
        logic = await worker.evaluate(checked)
        while not all(r.goal for r in logic.values()):
            assert any(r.locations for r in logic.values()), "everyone is blocked"
            for slot, r in logic.items():
                checked[slot] |= r.locations
            logic = await worker.evaluate(checked)
            rounds += 1
        assert rounds > 1
    finally:
        await worker.close()
    assert worker.process.returncode is not None and not worker.workdir.exists()


