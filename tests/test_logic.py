def zipped(entries: dict[str, bytes]) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, content in entries.items():
            archive.writestr(name, content)
    return buffer.getvalue()


def test_spoiler_logs_give_the_seed():
    spoiler = read_spoiler("AP_1_Spoiler.txt", SPOILER)
    assert (spoiler.seed, spoiler.plando, spoiler.version) == (DEV_SEED, "None", "0.6.8")
    assert read_spoiler("AP_1.zip", zipped({"AP_1/AP_1_Spoiler.txt": SPOILER, "AP_1/x.apz5": b""})) == spoiler

    without_plando = read_spoiler("s.txt", SPOILER.split(b"\n\n")[0])
    assert without_plando.plando == "bosses, connections, texts"

    with pytest.raises(LogicError, match="pas de spoiler log"):
        read_spoiler("AP_1.zip", zipped({"AP_1.archipelago": b""}))
    with pytest.raises(LogicError, match="Zip illisible"):
        read_spoiler("AP_1.zip", b"nope")
    with pytest.raises(LogicError, match="pas un spoiler log"):
        read_spoiler("notes.txt", b"hello")


def test_the_regenerated_seed_must_be_the_room():
    state = RoomState("x:1", seed_name="123", slots={1: SlotInfo(1, "Alice", "A"), 2: SlotInfo(2, "Bob", "B")})
    check_room(Generated("123", "0.6.8", "f", {1: ("Alice", "A"), 2: ("Bob", "B")}), state)
    state.seed_name = "W123"  # generated by a WebHost from yamls
    check_room(Generated("123", "0.6.8", "f", {1: ("Alice", "A"), 2: ("Bob", "B")}), state)

    with pytest.raises(LogicError, match="la seed ne correspond pas"):
        check_room(Generated("124", "0.6.8", "f", {1: ("Alice", "A"), 2: ("Bob", "B")}), state)
    with pytest.raises(LogicError, match="mêmes joueurs") as error:
        check_room(Generated("123", "0.6.8", "f", {1: ("Bob", "C"), 2: ("Alice", "A"), 3: ("Eve", "E")}), state)
    assert str(error.value).endswith(
        "\n- `Bob` (*B*) : dans la room, pas dans les yamls"
        "\n- `Bob` (*C*) : dans les yamls, pas dans la room"
        "\n- `Eve` (*E*) : dans les yamls, pas dans la room"
    )
    with pytest.raises(LogicError, match="mêmes joueurs") as error:
        check_room(Generated("123", "0.6.8", "f", {1: ("Bob", "B"), 2: ("Alice", "A")}), state)
    assert str(error.value).endswith(
        "\n- slot 1 : `Alice` (*A*) dans la room, `Bob` (*B*) regénéré"
        "\n- slot 2 : `Bob` (*B*) dans la room, `Alice` (*A*) regénéré"
    )


def dev_spoiler() -> str:
    archive = zipfile.ZipFile(SEEDS[-1])
    [name] = [n for n in archive.namelist() if n.endswith("_Spoiler.txt")]
    return read_spoiler(name, archive.read(name)).text


def test_spoilers_tell_what_a_regeneration_got_wrong():
    spoiler = dev_spoiler()
    assert "Playthrough" not in spoiler and spoiler_differences(spoiler, spoiler) == []
    # an old Manual apworld renames core options for every world: same options all the same
    assert spoiler_differences(spoiler, spoiler.replace("Death Link:                      ", "death_link: ")) == []

    other = spoiler.replace("Player 2: Bob\nGame:                            A Short Hike", "Player 2: Bob\nGame: Hike")
    other = other.replace("Total Strawberries:              20", "Total Strawberries:              30")
    assert spoiler_differences(spoiler, other) == [
        "- `Alice` · Total Strawberries : `20` dans le spoiler, `30` regénéré",
        "- `Bob` · Game : `A Short Hike` dans le spoiler, `Hike` regénéré",
    ]
    assert spoiler_differences(spoiler, other.replace("Player 3: Carol", "Player 3: Eve"), limit=3) == [
        "- `Alice` · Total Strawberries : `20` dans le spoiler, `30` regénéré",
        "- `Bob` · Game : `A Short Hike` dans le spoiler, `Hike` regénéré",
        "- `Carol` : dans le spoiler, pas regénéré",
        "- … et 1 autres",
    ]

    swapped = spoiler.replace("First Strawberry (Alice): Map Width (Carol)", "First Strawberry (Alice): Nothing")
    assert spoiler_differences(spoiler, swapped) == [
        "- Options identiques, mais pas les items.",
        "- Premier écart : `First Strawberry (Alice): Map Width (Carol)` dans le spoiler, "
        "`First Strawberry (Alice): Nothing` regénéré",
    ]
    short = spoiler.split("\n\nLocations:")[0]
    assert "génère avec `spoiler` à 1" in spoiler_differences(short, spoiler)[0]


